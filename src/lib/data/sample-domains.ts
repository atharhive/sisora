export function getDomainBySlug(slug: string): Domain | undefined {
  const normalized = slug.toLowerCase().replace(/\.si$/, "");
  return SAMPLE_DOMAINS.find(
    (d) => d.slug.toLowerCase() === normalized || d.name.toLowerCase() === `${normalized}.si`
  );
}

export function getAllCategories(): string[] {
  const set = new Set<string>();
  SAMPLE_DOMAINS.forEach((d) => {
    if (d.category) set.add(d.category);
  });
  return Array.from(set).sort();
}
